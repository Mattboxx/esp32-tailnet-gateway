"""Generate refc/x25519_mul_xtensa.S: the 256 x 256 -> 512-bit product of
X25519 (8 x 32-bit limbs) for Xtensa LX7, fully unrolled product scanning.

    python tools/gen_x25519_mul_xtensa.py

Column k of the product is the sum of a[i] * b[k-i]; it is kept in a 3-word
accumulator (c0 c1 c2) in registers and stored once per column, where the
compiled C loads and stores the accumulator word for every product. Two
register sets alternate so the loads of the next product are issued while the
current one is multiplied and added (no load-use stall, one instruction
between MULL and the first use of its result). Xtensa has no carry flag, so a
carry is SALTU of the sum against an addend; the high word of a 32 x 32
product is at most 2^32 - 2, so adding the low-word carry to it cannot wrap.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'external/microlink/components/microlink/components/wireguard_lwip/src/crypto/refc/x25519_mul_xtensa.S'

SETS = [('a5', 'a6', 'a7', 'a8'), ('a12', 'a13', 'a14', 'a15')]
C0, C1, C2 = 'a9', 'a10', 'a11'


def generate():
    pairs = []                        # (column, i, j) in product order
    for k in range(15):
        for i in range(max(0, k - 7), min(k, 7) + 1):
            pairs.append((k, i, k - i))
    lines = []
    emit = lines.append

    def load(p, s):
        _, i, j = pairs[p]
        ra, rb, _, _ = SETS[s]
        emit(f'    l32i    {ra}, a3, {4 * i}')
        emit(f'    l32i    {rb}, a4, {4 * j}')

    acc = [C0, C1, C2]
    load(0, 0)
    for p, (k, i, j) in enumerate(pairs):
        s = p % 2
        ra, rb, lo, hi = SETS[s]
        emit(f'    /* a[{i}] * b[{j}] */')
        emit(f'    mull    {lo}, {ra}, {rb}')
        emit(f'    muluh   {hi}, {ra}, {rb}')
        if p + 1 < len(pairs):
            load(p + 1, 1 - s)        # next product's operands, other set
        c0, c1, c2 = acc
        emit(f'    add     {c0}, {c0}, {lo}')
        emit(f'    saltu   {lo}, {c0}, {lo}')
        emit(f'    add     {hi}, {hi}, {lo}')
        emit(f'    add     {c1}, {c1}, {hi}')
        emit(f'    saltu   {hi}, {c1}, {hi}')
        emit(f'    add     {c2}, {c2}, {hi}')
        last_in_column = p + 1 == len(pairs) or pairs[p + 1][0] != k
        if last_in_column:
            emit(f'    s32i    {c0}, a2, {4 * k}            /* out[{k}] */')
            emit(f'    movi    {c0}, 0')
            acc = [c1, c2, c0]        # rename: next column's c0, c1, c2
    emit(f'    s32i    {acc[0]}, a2, 60           /* out[15] */')
    body = '\n'.join(lines)
    return f'''/* SPDX-License-Identifier: MIT
 * GENERATED by tools/gen_x25519_mul_xtensa.py; edit the generator, not this file.
 *
 * X25519 field multiplication, product only: out[16] = a[8] * b[8]
 * (32-bit limbs, little endian), for Xtensa LX7 (ESP32-S3), Mattboxx 2026-11-08.
 * Fully unrolled product scanning with the column sum in a 3-word register
 * accumulator; see the generator for the scheme. The reduction mod
 * 2^255 - 19 stays in C (x25519.c), which compares this routine with its C
 * product before first use and keeps C if they differ.
 *
 * void x25519_mul_xtensa(uint32_t out[16], const uint32_t a[8], const uint32_t b[8]);
 * out must not overlap a or b.
 */
#if defined(__XTENSA__)

    .section .text.x25519_mul_xtensa, "ax"
    .literal_position
    .align  4
    .global x25519_mul_xtensa
    .type   x25519_mul_xtensa, @function
x25519_mul_xtensa:
    entry   a1, 32
    movi    {C0}, 0
    movi    {C1}, 0
    movi    {C2}, 0
{body}
    retw
    .size   x25519_mul_xtensa, . - x25519_mul_xtensa

#endif /* __XTENSA__ */
'''


if __name__ == '__main__':
    text = generate()
    OUT.write_bytes(text.replace('\n', '\r\n').encode('ascii'))
    print(f'{OUT.relative_to(ROOT)}: {text.count(chr(10))} lines, {text.count("mull ")} products')
